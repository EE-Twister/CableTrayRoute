import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

for (const count of [25, 50]) test(`${count} loads show the 25 hp exact research assembly and preserve its blocked status`, async ({ page }) => {
  await page.goto(server.url('designsynthesis.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Load motor breaker research sample', exact: true }).click();
  await page.getByText('Advanced equipment JSON / CSV-ready structure').click();
  const equipment = page.locator('#synthesis-equipment');
  const original = JSON.parse(await equipment.inputValue());
  const rows = Array.from({ length: count }, (_, index) => {
    const row = { ...structuredClone(original[index % original.length]), id: `L-${index}`, tag: `L-${index}` };
    if (index !== 0) delete row.motor;
    return row;
  });
  Object.assign(rows[0], { kw: Math.sqrt(3) * 480 * 29.5 * 0.85 / 1000, powerFactor: 0.85 });
  Object.assign(rows[0].motor, { nameplateHorsepower: 25, nameplateCurrentA: 29.5, fullLoadCurrentA: 34, fullLoadCurrentBasis: { reference: 'Synthetic design-current case' }, lockedRotorCurrentA: 183, lockedRotorPowerFactor: 0.3, rotorType: 'squirrel-cage' });
  await equipment.fill(JSON.stringify(rows));
  await page.getByRole('combobox', { name: 'Proposed TM230 instantaneous pickup (A)', exact: true }).selectOption('350');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  const review = page.locator('#synthesis-motor-starter-review');
  await expect(review).toContainText('3RT2036-1NB30 + 3RU2136-4EB0 + 3VA5150-6EC31-0AA0');
  await expect(review).toContainText('25 kA conditional combination rating');
  await expect(review).toContainText('250, 300, 350, 400, 450, 500 A');
  await expect(review).toContainText('No qualified exact 50 A timing envelope');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const pending = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'));
  const candidate = proposal.motorStarterCandidates.cases[0].candidate;
  expect(candidate.branchCircuitBreaker.instantaneousPickupA).toBe(350);
  expect(candidate.selectedForApply).toBe(false);
  const cable = proposal.cables.find(row => row.loadId === 'L-0');
  expect(cable.motor.branchBreakerAmpacityFloorA).toBe(50);
  const connection = proposal.oneLine.sheets[0].connections.find(row => row.cableRef === cable.id);
  expect(connection.cable.protectiveDevice.catalogNumber).toBe('3VA5150-6EC31-0AA0');
  expect(connection.cable.protectiveDevice.proposedInstantaneousPickupA).toBe(350);
  expect(proposal.issues.some(issue => issue.code === 'MOTOR_PROTECTION_UNRESOLVED')).toBe(true);
  const reportPending = page.waitForEvent('download');
  await page.locator('#synthesis-download-report').click();
  const report = await fs.readFile(await (await reportPending).path(), 'utf8');
  expect(report).toContain('3VA5150-6EC31-0AA0');
  expect(report).toContain('No qualified exact 50 A timing envelope');
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Proposed TM230 instantaneous pickup (A)', exact: true })).toHaveValue('350');
});

test('manufacturer motor example retains source data and the correctly matched research relay', async ({ page }) => {
  await page.goto(server.url('designsynthesis.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Load manufacturer motor example' }).click();
  await expect(page.locator('#synthesis-status')).toContainText('Manufacturer motor example loaded');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  const review = page.locator('#synthesis-motor-starter-review');
  await expect(review).toContainText('3RT2027-1BB40 + 3RU2126-4BB0');
  await expect(review).toContainText('candidate relay dial 16.8 A');
  await expect(review).toContainText('protection blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  await expect(page.locator('#synthesis-one-line-preview svg')).toContainText('Motor protection unresolved');
  const pending = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'));
  const motor = proposal.inputs.original.equipment[0];
  expect(motor.motor.nameplateCurrentA).toBe(16.8);
  expect(motor.motor.fullLoadCurrentA).toBe(14);
  expect(motor.motor.lockedRotorPowerFactor).toBe(0.254);
  expect(motor.sourceDocuments[0].title).toContain('typical performance, not guaranteed');
  expect(motor.provenance.note).toContain('illustrative');
  expect(proposal.motorStarterCandidates.cases[0].candidate.conditionalCombination.maximumBreakerCurrentA).toBe(40);
  expect(proposal.motorStarterCandidates.cases[0].candidate.selectedForApply).toBe(false);
});

