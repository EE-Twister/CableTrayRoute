import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

for (const count of [25, 50]) test(`${count} equipment loads keep per-motor enclosure bases through review and reload`, async ({ page }) => {
  test.setTimeout(120000);
  await page.goto(server.url('equipmentlist.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForFunction(() => Boolean(window.dataStore));
  const rows = Array.from({ length: count }, (_, index) => ({ id: `E-${index}`, tag: `E-${index}`, category: index < 3 ? 'Motor' : 'Load', voltage: 480, phases: 3, x: 10 + index * 3, y: 0, z: 0, powerFactor: index < 3 ? 0.86 : 0.9, kw: index < 3 ? Math.sqrt(3) * 480 * 48 * 0.86 / 1000 : 2, duty: 'continuous', ownerNote: `keep-${index}`, ...(index < 3 ? { ratingsBasis: 'electrical-input-kW', motorRatedVoltageV: 460, motorFullLoadCurrentA: 52, motorFullLoadCurrentReference: 'Synthetic design current', motorNameplateCurrentA: 48, motorNameplateHorsepower: 40, motorNameplateFrequencyHz: 60, motorLockedRotorCurrentA: 338, motorLockedRotorPowerFactor: 0.27, motorStarterType: 'dol', motorRotorType: 'squirrel-cage', motorInstantaneousPickupA: 'none' } : {}) }));
  await page.evaluate(items => { window.dataStore.setEquipment(items); window.dataStore.setLoads([]); }, rows);
  await page.reload();
  await expect(page.locator('#equipment-table tbody tr')).toHaveCount(count);
  await page.getByRole('button', { name: 'Full', exact: true }).click();
  const tableRows = page.locator('#equipment-table tbody tr');
  const hot = tableRows.nth(1).locator('td[data-column-key="motorBreakerAmbientTemperatureC"] input');
  await hot.fill('70'); await hot.press('Tab');
  const hotReference = tableRows.nth(1).locator('td[data-column-key="motorBreakerAmbientReference"] input');
  await hotReference.fill('Synthetic hot enclosure'); await hotReference.press('Tab');
  const unset = tableRows.nth(2).locator('td[data-column-key="motorBreakerAmbientTemperatureC"] input');
  await unset.fill('none'); await unset.press('Tab');
  await expect.poll(async () => (await page.evaluate(() => window.dataStore.getEquipment()))[1].motorBreakerAmbientReference).toBe('Synthetic hot enclosure');
  await page.reload();
  const stored = await page.evaluate(() => window.dataStore.getEquipment());
  expect(stored[1].motorBreakerAmbientTemperatureC).toBe('70');
  expect(stored[2].motorBreakerAmbientTemperatureC).toBe('none');
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.waitForFunction(() => Boolean(window.dataStore));
  await page.evaluate(() => { window.currentProjectId = 'Motor enclosures'; window.dataStore.setProjectMeta({ id: 'Motor enclosures', name: 'Motor enclosures' }); if (!window.dataStore.saveProject('Motor enclosures')) throw new Error('Save failed'); });
  await page.getByRole('button', { name: 'Load motor breaker research sample', exact: true }).click();
  await expect(page.locator('#synthesis-status')).toContainText('Synthetic breaker research sample loaded');
  await page.getByRole('combobox', { name: '70 A breaker enclosure temperature (°C)' }).selectOption('50');
  await page.getByLabel('Breaker enclosure temperature reference', { exact: true }).fill('Synthetic project enclosure');
  await page.getByLabel('Breaker enclosure temperature reference', { exact: true }).press('Tab');
  const picker = page.locator('#synthesis-project-equipment');
  await expect(picker.locator('[data-project-equipment-select]:not([disabled])')).toHaveCount(count);
  for (const row of stored) await picker.locator(`[data-project-equipment-select="${row.id}"]`).check();
  for (const basis of ['electricalInputKW', 'voltageLineToLine', 'coordinatesFeet']) await picker.locator(`[data-project-equipment-ack="${basis}"]`).check();
  await picker.locator('[data-project-equipment-review]').click();
  await expect(picker).toContainText(`${count} selected pair(s)`);
  await expect(picker).toContainText('70 °C (Synthetic hot enclosure)');
  await expect(picker).toContainText('explicitly not specified');
  await picker.locator('[data-project-equipment-copy]').click();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const pending = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'));
  expect(proposal.loads).toHaveLength(count);
  for (const [id, basis, status] of [[stored[0].id, 'project', 'unevaluated'], [stored[1].id, 'motor', 'fail'], [stored[2].id, 'motor-unset', 'unevaluated']]) {
    const result = proposal.motorStarterCandidates.cases.find(item => item.motorId === id);
    const check = result.candidates[0].checks.find(item => item.id === 'breakerAmbientOperatingCurrent');
    expect(check.evidence.basis).toBe(basis);
    expect(check.status).toBe(status);
  }
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Motor breaker enclosure temperature 2' })).toHaveValue('70');
  await expect(page.getByRole('combobox', { name: 'Motor breaker enclosure temperature 3' })).toHaveValue('none');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  expect((await page.evaluate(() => window.dataStore.getEquipment()))[1].ownerNote).toBe('keep-1');
});
