import { test, expect } from '@playwright/test';
import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

test('edits corridor graph, retains explicit closures, and reflects them in the route preview', async ({ page }) => {
  test.setTimeout(120000);
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  const editor = page.locator('#synthesis-corridor-editor');
  await expect(editor.locator('[data-corridor-add="edges"]')).toBeVisible();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal generated');
  await expect(page.locator('.synthesis-route-preview title').filter({ hasText: 'Permitted corridor E25' })).toHaveCount(1);
  const routeReview = page.locator('#synthesis-route-review');
  const circuit = await routeReview.locator('[data-route-cable]').first().getAttribute('data-route-cable');
  await expect(routeReview).toContainText('x and y share a scale');
  await routeReview.getByLabel('Inspect proposed circuit route').selectOption(circuit);
  await expect(routeReview).toContainText(`Route ${circuit}: routed`);
  const visibleIds = await routeReview.locator('[data-route-cable]').evaluateAll(elements => [...new Set(elements.map(element => element.getAttribute('data-route-cable')))]);
  expect(visibleIds).toEqual([circuit]);
  await expect(routeReview).toContainText('Start x / y / z (ft)');
  await routeReview.getByLabel('Inspect proposed circuit route').selectOption('');
  expect(await routeReview.locator('[data-route-cable]').count()).toBeGreaterThan(visibleIds.length);
  await editor.locator('[data-corridor-kind="edges"][data-corridor-index="4"][data-corridor-field="permission"]').selectOption('closed');
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await expect(routeReview).toHaveCount(0);
  const e14From = editor.locator('[data-corridor-kind="edges"][data-corridor-index="3"][data-corridor-field="from"]');
  await e14From.fill('n1');
  await e14From.press('Tab');
  await editor.locator('[data-corridor-add="nodes"]').click();
  await expect(editor.locator('[data-corridor-kind="nodes"][data-corridor-index="9"][data-corridor-field="id"]')).toHaveValue('');
  await editor.locator('[data-corridor-remove="nodes"][data-corridor-index="9"]').click();
  await editor.locator('[data-corridor-add="edges"]').click();
  await expect(editor.locator('[data-corridor-kind="edges"][data-corridor-index="10"][data-corridor-field="permission"]')).toHaveValue('closed');
  await editor.locator('[data-corridor-remove="edges"][data-corridor-index="10"]').click();
  let graph = JSON.parse(await page.locator('#synthesis-corridors').inputValue());
  expect(graph.edges[4].permitted).toBe(false);
  expect(graph.edges[3].from).toBe('n1');
  await page.reload();
  graph = JSON.parse(await page.locator('#synthesis-corridors').inputValue());
  expect(graph.edges[4].permitted).toBe(false);
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal generated');
  await expect(page.locator('#synthesis-output')).toContainText('Route preview');
  await expect(page.locator('.synthesis-route-preview title').filter({ hasText: 'Permitted corridor E25' })).toHaveCount(0);
  await expect(page.locator('.synthesis-route-preview title').filter({ hasText: 'Permitted corridor E14' })).toHaveCount(1);
  const download = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await download).path(), 'utf8'));
  const traySegments = proposal.routeResults.batchResults.flatMap(route => route.route_segments || []).filter(segment => segment.type === 'tray');
  expect(traySegments.length).toBeGreaterThan(0);
  expect(traySegments.some(segment => segment.tray_id === 'E25')).toBe(false);
  await page.locator('#synthesis-corridors').fill('{invalid');
  await expect(editor).toContainText('Correct invalid corridor JSON');
  await expect(editor.locator('[data-corridor-add]')).toHaveCount(0);
});
