import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

async function download(page, selector) {
  const pending = page.waitForEvent('download');
  await page.locator(selector).click();
  const value = await pending;
  const chunks = [];
  for await (const chunk of await value.createReadStream()) chunks.push(chunk);
  return Buffer.concat(chunks).toString();
}

test('imported motor classification with whitespace blocks an ordinary-load proposal', async ({ page }) => {
  const input = JSON.parse(await fs.readFile(path.join(root, 'samples/design-synthesis-industrial.json'), 'utf8'));
  input.equipment = input.equipment.slice(0, 25);
  input.equipment[0].type = ' Motor ';
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await expect(page.locator('#synthesis-generate')).toBeEnabled();
  await page.locator('#synthesis-import').setInputFiles({ name: 'motor-classification.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(input)) });
  await expect(page.locator('#synthesis-status')).toContainText('Imported motor-classification.json');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const proposal = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(proposal.status).toBe('blocked');
  expect(proposal.issues.some(row => row.code === 'MOTOR_DATA_REQUIRED' && row.path === 'equipment[0].motor')).toBe(true);
  expect(proposal.inputs.original.equipment[0].type).toBe(' Motor ');
});

