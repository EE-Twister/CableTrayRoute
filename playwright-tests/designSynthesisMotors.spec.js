test('motor inputs survive table edits and export while unresolved protection prevents Apply', async ({ page }, testInfo) => {
  const input = JSON.parse(await fs.readFile(path.join(root, 'samples/design-synthesis-industrial.json'), 'utf8'));
  input.equipment = input.equipment.slice(0, 25).map(row => ({ ...row, kw: 2 }));
  input.equipment[0] = { ...input.equipment[0], kw: 8, powerFactor: 0.86, duty: 'continuous', ratingsBasis: 'electrical-input-kW', motor: {
    ratedVoltageV: 460, fullLoadCurrentA: 14, fullLoadCurrentBasis: { reference: 'Synthetic browser test current basis.' },
    nameplateCurrentA: 12.8, lockedRotorCurrentA: 90, lockedRotorPowerFactor: 0.3, starterType: 'dol',
  } };
  input.supply.motorStartingImpedance = { rOhm: 0.006, xOhm: 0.015, reference: 'Synthetic browser test source impedance within the 20 kA external source bound.' };
  input.criteria.motorStarting = { minimumVoltagePu: 0.8 };
  await page.goto(server.url('designsynthesis.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.locator('#synthesis-import').setInputFiles({ name: 'motors.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(input)) });
  await expect(page.locator('#synthesis-status')).toContainText('Imported motors.json');
  await page.getByRole('spinbutton', { name: 'kw 1', exact: true }).fill('9');
  await page.getByRole('spinbutton', { name: 'kw 1', exact: true }).press('Tab');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const proposal = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(proposal.loads).toHaveLength(25);
  expect(proposal.loads[0].motor).toEqual(input.equipment[0].motor);
  expect(proposal.loads[0].kw).toBe(9);
  expect(proposal.cables.find(row => row.loadId === input.equipment[0].id).ampacityA).toBeGreaterThanOrEqual(17.5);
  expect(proposal.motorStartingValidation.cases).toHaveLength(1);
  expect(proposal.motorStartingValidation.cases[0].motorCurrentA).toBeGreaterThan(0);
  expect(proposal.sourceFaultConsistency.status).toBe('pass');
  expect(proposal.sourceFaultConsistency.impliedSourceOnlyFaultCurrentKA).toBeCloseTo(17.153800557404715, 8);
  expect(proposal.sourceFaultConsistency.declaredAvailableFaultCurrentKA).toBe(20);
  await expect(page.locator('#synthesis-source-fault-review')).toContainText('17.153801 kA');
  const overload = proposal.motorOverloadCandidates.cases[0].candidate;
  expect(overload.catalogNumber).toBe('3RU2116-4AB0');
  expect(overload.settingRangeA).toEqual([11, 16]);
  expect(overload.dialSettingA).toBe(12.8);
  expect(proposal.motorOverloadCandidates.status).toBe('screening_only');
  await expect(page.locator('#synthesis-motor-overload-review')).toContainText('3RU2116-4AB0');
  await expect(page.locator('#synthesis-motor-overload-review')).toContainText('12.8 A nameplate dial');
  expect(proposal.issues.some(row => /motor.*protection|overload/i.test(row.message))).toBe(true);
  const report = (await download(page, '#synthesis-download-report')).split('Complete JSON payload:')[0];
  expect(report).toMatch(/motor/i);
  expect(report).toMatch(/locked.rotor|starting/i);
  expect(report).toMatch(/overload|coordination/i);
  expect(report).not.toContain('[object Object]');
  expect(report).toContain('"rOhm":0.006');
  expect(report).toContain('minimum network voltage');
  expect(report).toContain('3RU2116-4AB0');
  expect(report).toContain('11–16 A range');
  expect(report).toContain('12.8 A nameplate dial');
  expect(report).toContain('manual_overload_relay_3RU2_3RB3_en-US.pdf');
  expect(report).toContain('range screening only');
  expect(report).toContain('Uninspected Siemens data-sheet follow-up');
  expect(report).toContain('Conditional source fault-bound comparison: pass');
  expect(report).toContain('Complete local fault-duty and motor-contribution review: unevaluated');
  expect(report).toContain('Declared external-source upper bound: 20 kA');
  await fs.writeFile(testInfo.outputPath('motor-preliminary-report.txt'), report);
  await page.locator('#synthesis-motor-review').screenshot({ path: testInfo.outputPath('motor-review.png') });
  await page.locator('#synthesis-motor-overload-review').screenshot({ path: testInfo.outputPath('motor-overload-review.png') });
  const equipmentJson = page.locator('#synthesis-equipment');
  const changed = JSON.parse(await equipmentJson.inputValue());
  changed[0].motor.lockedRotorCurrentA = 120;
  changed[0].motor.nameplateCurrentA = 18;
  await page.getByText('Advanced equipment JSON / CSV-ready structure', { exact: true }).click();
  await equipmentJson.fill(JSON.stringify(changed));
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await expect(page.locator('#synthesis-motor-overload-review')).toHaveCount(0);
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  const revised = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(revised.motorOverloadCandidates.cases[0].candidate.catalogNumber).toBe('3RU2126-4CB0');
  expect(revised.motorOverloadCandidates.cases[0].candidate.dialSettingA).toBe(18);
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  await page.getByText('Advanced supply JSON', { exact: true }).click();
  const supplyJson = page.locator('#synthesis-supply');
  const changedSource = JSON.parse(await supplyJson.inputValue());
  changedSource.availableFaultCurrentKA = 10;
  await supplyJson.fill(JSON.stringify(changedSource));
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await expect(page.locator('#synthesis-source-fault-review')).toHaveCount(0);
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  const inconsistent = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(inconsistent.sourceFaultConsistency.status).toBe('blocked');
  expect(inconsistent.sourceFaultConsistency.declaredAvailableFaultCurrentKA).toBe(10);
  expect(inconsistent.motorStartingValidation.status).toBe('blocked');
  expect(inconsistent.motorStartingValidation.cases).toHaveLength(0);
  expect(inconsistent.loads).toHaveLength(25);
  expect(inconsistent.motorStartingValidation.modelInputFingerprint).not.toBe(revised.motorStartingValidation.modelInputFingerprint);
  await expect(page.locator('#synthesis-source-fault-review')).toContainText('implied-exceeds-declared-bound');
  const inconsistentReport = (await download(page, '#synthesis-download-report')).split('Complete JSON payload:')[0];
  expect(inconsistentReport).toContain('Conditional source fault-bound comparison: blocked');
  expect(inconsistentReport).toContain('Declared external-source upper bound: 10 kA');
  await fs.writeFile(testInfo.outputPath('source-fault-blocked-report.txt'), inconsistentReport);
  await page.locator('#synthesis-source-fault-review').screenshot({ path: testInfo.outputPath('source-fault-blocked-review.png') });
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  changedSource.availableFaultCurrentKA = 20;
  await supplyJson.fill(JSON.stringify(changedSource));
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-source-fault-review')).toContainText('below-declared-bound');
  const restored = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(restored.sourceFaultConsistency.status).toBe('pass');
  expect(restored.motorStartingValidation.status).toBe('pass');
  expect(restored.status).toBe('blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
});
