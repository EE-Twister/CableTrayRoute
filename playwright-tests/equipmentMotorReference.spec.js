import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

test('reviewed motor design current is saved, blocks stale changes, and can be refreshed', async ({ page }) => {
  await page.goto(server.url('equipmentlist.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForFunction(() => Boolean(window.dataStore));
  await page.evaluate(() => window.dataStore.setEquipment([{ id: 'M1', tag: 'M1', category: 'Motor', voltage: 480, phases: 3, kw: 8, powerFactor: 0.8, duty: 'continuous', x: 0, y: 0, z: 0, motorRatedVoltageV: 460, motorNameplateHorsepower: 10, motorNameplateCurrentA: 16.8, motorNameplateFrequencyHz: 60, motorRotorType: 'squirrel-cage', motorStarterType: 'dol', motorLockedRotorCurrentA: 121, motorLockedRotorPowerFactor: 0.254 }]));
  await page.reload();
  await page.locator('#equipment-table tbody tr').first().locator('.row-select').check();
  await page.getByText('Bulk Edit', { exact: true }).click();
  await page.getByRole('button', { name: 'Review Motor Design Current' }).click();
  let dialog = page.getByRole('dialog', { name: 'Review Motor Design Current' });
  await expect(dialog).toContainText('nameplate 16.8 A, table 14 A, proposed 16.8 A');
  await dialog.getByRole('button', { name: 'Apply Reviewed Currents' }).click();
  await expect(dialog).toBeHidden();
  await page.reload();
  let row = (await page.evaluate(() => window.dataStore.getEquipment()))[0];
  expect(row.motorFullLoadCurrentA).toBe(16.8);
  expect(row.motorFullLoadCurrentReference).toContain('nyecountynv.gov');
  await page.getByRole('button', { name: 'Full', exact: true }).click();
  const nameplate = page.locator('#equipment-table tbody tr').first().locator('td[data-column-key="motorNameplateCurrentA"] input');
  await nameplate.fill('20');
  await nameplate.press('Tab');
  await expect.poll(async () => Number((await page.evaluate(() => window.dataStore.getEquipment()))[0].motorNameplateCurrentA)).toBe(20);
  await page.reload();
  await page.locator('#equipment-table tbody tr').first().locator('.row-select').check();
  await page.getByText('Bulk Edit', { exact: true }).click();
  await page.getByRole('button', { name: 'Review Motor Design Current' }).click();
  dialog = page.getByRole('dialog', { name: 'Review Motor Design Current' });
  await expect(dialog).toContainText('nameplate 20 A, table 14 A, proposed 20 A');
  await dialog.getByRole('button', { name: 'Apply Reviewed Currents' }).click();
  row = (await page.evaluate(() => window.dataStore.getEquipment()))[0];
  expect(row.motorFullLoadCurrentA).toBe(20);
});

test('motor reference survives Equipment List, project review, generation and reload', async ({ page }) => {
  test.setTimeout(90000);
  await page.goto(server.url('equipmentlist.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForFunction(() => Boolean(window.dataStore));
  const rows = Array.from({ length: 25 }, (_, index) => ({ id: `EQ-${index}`, tag: `EQ-${index}`, category: index === 0 ? 'Motor' : 'Load', kw: index === 0 ? Math.sqrt(3) * 460 * 16.8 * 0.61 / 1000 : 2, voltage: 480, phases: 3, powerFactor: index === 0 ? 0.61 : 0.9, duty: 'continuous', x: 10 + index * 3, y: 0, z: 0, ownerNote: `keep-${index}`, ...(index === 0 ? { motorFullLoadCurrentA: 14, motorFullLoadCurrentReference: 'Illustrative design current; applicability unverified', motorRotorType: 'squirrel-cage', motorInstantaneousPickupA: '180' } : {}) }));
  await page.evaluate(rows => { window.dataStore.setEquipment(rows); window.dataStore.setLoads([]); }, rows);
  await page.reload();
  await expect(page.locator('#equipment-table tbody tr')).toHaveCount(25);
  await page.locator('#equipment-table tbody tr').first().locator('.row-select').check();
  await page.getByText('Bulk Edit', { exact: true }).click();
  await page.getByRole('button', { name: 'Use Motor Reference Data' }).click();
  const dialog = page.getByRole('dialog', { name: 'Use Motor Reference Data' });
  await expect(dialog).toContainText('Typical data are not guaranteed');
  await dialog.getByLabel('Manufacturer motor model').selectOption('baldor-gnem2332t-460-60');
  await dialog.getByRole('button', { name: 'Apply Reference Data' }).click();
  await expect(dialog).toBeHidden();
  let stored = await page.evaluate(() => window.dataStore.getEquipment());
  expect(stored[0].motorNameplateCurrentA).toBe(16.8);
  expect(stored[0].motorFullLoadCurrentA).toBe(14);
  expect(stored[0].motorDataReference).toContain('GNEM2332T');
  expect(stored[0].ownerNote).toBe('keep-0');
  expect(stored[1].motorDataReference || '').toBe('');
  await page.reload();
  stored = await page.evaluate(() => window.dataStore.getEquipment());
  expect(stored[0].motorDataReference).toContain('not verified installed');
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.waitForFunction(() => Boolean(window.dataStore));
  await page.evaluate(() => { window.currentProjectId = 'Motor handoff'; window.dataStore.setProjectMeta({ id: 'Motor handoff', name: 'Motor handoff' }); if (!window.dataStore.saveProject('Motor handoff')) throw new Error('Save failed'); });
  await page.getByRole('button', { name: 'Load motor breaker research sample' }).click();
  const picker = page.locator('#synthesis-project-equipment');
  await expect(picker.locator('[data-project-equipment-select]:not([disabled])')).toHaveCount(25);
  for (const row of stored) await picker.locator(`[data-project-equipment-select="${row.id}"]`).check();
  for (const basis of ['electricalInputKW', 'voltageLineToLine', 'coordinatesFeet']) await picker.locator(`[data-project-equipment-ack="${basis}"]`).check();
  await picker.locator('[data-project-equipment-review]').click();
  await expect(picker).toContainText('25 selected pair(s)');
  await picker.locator('[data-project-equipment-copy]').click();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-motor-starter-review')).toContainText('3RU2126-4BB0');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const pending = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'));
  expect(proposal.loads).toHaveLength(25);
  expect(proposal.inputEvidence.records.equipment[0].sourceDocuments[0]).toContain('GNEM2332T');
  expect(proposal.inputs.original.equipment[0].motor.fullLoadCurrentBasis.reference).toContain('applicability unverified');
  expect(proposal.inputs.original.equipment[0].motor.instantaneousPickupA).toBe(180);
  expect(proposal.motorStarterCandidates.cases[0].candidate.branchCircuitBreaker.instantaneousPickupA).toBe(180);
  expect(proposal.motorStarterCandidates.cases[0].candidate.branchCircuitBreaker.instantaneousPickupBasis).toBe('motor');
  expect((await page.evaluate(() => window.dataStore.getEquipment()))[0].ownerNote).toBe('keep-0');
});

for (const count of [25, 50]) test(`${count} loads retain an explicitly selected typical motor operating basis`, async ({ page }) => {
  test.setTimeout(120000);
  await page.goto(server.url('equipmentlist.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForFunction(() => Boolean(window.dataStore));
  const rows = Array.from({ length: count }, (_, index) => ({ id: `EQ-${index}`, tag: `EQ-${index}`, category: index === 0 ? 'Motor' : 'Load', voltage: 480, phases: 3, x: 10 + index * 3, y: 0, z: 0, ownerNote: `keep-${index}`, ...(index === 0 ? { motorFullLoadCurrentA: 16.8, motorFullLoadCurrentReference: 'Synthetic design current; applicability unverified', motorRotorType: 'squirrel-cage' } : { kw: 2, powerFactor: 0.9, duty: 'continuous' }) }));
  await page.evaluate(items => { window.dataStore.setEquipment(items); window.dataStore.setLoads([]); }, rows);
  await page.reload();
  await expect(page.locator('#equipment-table tbody tr')).toHaveCount(count);
  await page.locator('#equipment-table tbody tr').first().locator('.row-select').check();
  await page.getByText('Bulk Edit', { exact: true }).click();
  await page.getByRole('button', { name: 'Use Motor Reference Data' }).click();
  const dialog = page.getByRole('dialog', { name: 'Use Motor Reference Data' });
  const choice = dialog.getByLabel('Use typical 100%-rated-load operating kW and power factor');
  await expect(choice).not.toBeChecked();
  await dialog.getByLabel('Manufacturer motor model').selectOption('baldor-gnem2332t-460-60');
  await expect(dialog).toContainText('8.186 kW input at 460 V and rated load');
  await choice.check();
  await dialog.getByRole('button', { name: 'Apply Reference Data' }).click();
  await expect(dialog).toBeHidden();
  await page.reload();
  const stored = await page.evaluate(() => window.dataStore.getEquipment());
  expect(stored[0].kw).toBe(10 * 0.7457 / 0.911);
  expect(stored[0].powerFactor).toBe(0.61);
  expect(stored[0].motorOperatingBasis.sourceSha256).toBe('7af275fea860d9d38ccbfce69f802e1d58fa902dbd0b36a1f91cc25508c81de5');
  expect(stored[0].ownerNote).toBe('keep-0');
  expect(stored[1].motorOperatingBasis).toBeUndefined();
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.waitForFunction(() => Boolean(window.dataStore));
  await page.evaluate(() => { window.currentProjectId = 'Motor operating reference'; window.dataStore.setProjectMeta({ id: 'Motor operating reference', name: 'Motor operating reference' }); if (!window.dataStore.saveProject('Motor operating reference')) throw new Error('Save failed'); });
  await page.getByRole('button', { name: 'Load motor breaker research sample' }).click();
  const picker = page.locator('#synthesis-project-equipment');
  await expect(picker.locator('[data-project-equipment-select]:not([disabled])')).toHaveCount(count);
  for (const row of stored) await picker.locator(`[data-project-equipment-select="${row.id}"]`).check();
  for (const basis of ['electricalInputKW', 'voltageLineToLine', 'coordinatesFeet']) await picker.locator(`[data-project-equipment-ack="${basis}"]`).check();
  await picker.locator('[data-project-equipment-review]').click();
  await expect(picker).toContainText(`${count} selected pair(s)`);
  await expect(picker).toContainText('Typical 100%-rated-load GNEM2332T operating basis at 460 V');
  await expect(picker).toContainText('not guaranteed or verified installed');
  await picker.locator('[data-project-equipment-copy]').click();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const pending = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'));
  expect(proposal.loads).toHaveLength(count);
  expect(proposal.issues.some(item => item.code === 'MOTOR_PROTECTION_UNRESOLVED')).toBe(true);
  expect(proposal.inputs.original.equipment[0].motorOperatingBasis).toEqual(stored[0].motorOperatingBasis);
  expect(proposal.inputEvidence.records.equipment[0].values.kw.basis).toBe('manufacturer-reference-derived');
  expect(proposal.inputEvidence.records.equipment[0].values.powerFactor.basis).toBe('manufacturer-reference-derived');
});
