import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

test('copy a fault-study source only after reviewing its applicability to starting', async ({ page }) => {
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Load motor fault network sample', exact: true }).click();
  await page.getByText('Advanced supply JSON').click();
  const editor = page.locator('#synthesis-supply');
  const source = JSON.parse(await editor.inputValue());
  delete source.motorStartingImpedance;
  await editor.fill(JSON.stringify(source));
  await editor.press('Tab');
  await page.getByRole('button', { name: 'Review starting source impedance' }).click();
  const dialog = page.getByRole('dialog', { name: 'Review starting source impedance' });
  await dialog.getByRole('button', { name: 'Copy supply equivalent from fault study' }).click();
  await expect(dialog.getByLabel('Starting-case source X/R')).toHaveValue('2.5');
  await expect(dialog.getByLabel('Source-case and X/R reference')).toHaveValue(/Synthetic utility-source/);
  await expect(dialog.getByLabel('These values describe the same source-only starting case at the stated source voltage.')).not.toBeChecked();
  await dialog.getByLabel('These values describe the same source-only starting case at the stated source voltage.').check();
  await dialog.getByLabel('Starting-case source fault current (kA)').fill('16');
  await expect(dialog.getByLabel('Source-case and X/R reference')).toHaveValue('');
  await expect(dialog.getByLabel('These values describe the same source-only starting case at the stated source voltage.')).not.toBeChecked();
  await dialog.getByRole('button', { name: 'Copy supply equivalent from fault study' }).click();
  await dialog.getByRole('button', { name: 'Use reviewed impedance' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Confirm the current and X/R');
  await dialog.getByLabel('These values describe the same source-only starting case at the stated source voltage.').check();
  await dialog.getByRole('button', { name: 'Use reviewed impedance' }).click();
  await expect(dialog).toBeHidden();
  const saved = JSON.parse(await editor.inputValue());
  expect(saved.motorStartingImpedance.rOhm).toBeCloseTo(0.006, 14);
  expect(saved.motorStartingImpedance.xOhm).toBeCloseTo(0.015, 14);
  expect(saved.motorStartingImpedance.reference).toContain('Fault-study source snapshot');
  await page.reload();
  expect(JSON.parse(await editor.inputValue()).motorStartingImpedanceBasis.xOverR).toBe(2.5);
});

for (const count of [25, 50]) test(`${count} loads use a reviewed source starting case and reject a stale basis`, async ({ page }) => {
  test.setTimeout(120000);
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Load motor breaker research sample', exact: true }).click();
  await expect(page.locator('#synthesis-status')).toContainText('Synthetic breaker research sample loaded');
  await page.getByText('Advanced equipment JSON / CSV-ready structure').click();
  const equipment = page.locator('#synthesis-equipment');
  const original = JSON.parse(await equipment.inputValue());
  const rows = Array.from({ length: count }, (_, index) => index === 0 ? { ...original[0], id: 'M-0', tag: 'M-0' } : { ...original[1 + (index - 1) % (original.length - 1)], id: `L-${index}`, tag: `L-${index}`, kw: 2, powerFactor: 0.9, duty: 'continuous' });
  await equipment.fill(JSON.stringify(rows));
  await equipment.press('Tab');
  await page.getByRole('button', { name: 'Review starting source impedance' }).click();
  let dialog = page.getByRole('dialog', { name: 'Review starting source impedance' });
  await dialog.getByLabel('Starting-case source fault current (kA)').fill('17');
  await dialog.getByLabel('Starting-case source X/R').fill('2.5');
  await dialog.getByLabel('Source-case and X/R reference').fill('Synthetic starting source case');
  await dialog.getByLabel('These values describe the same source-only starting case at the stated source voltage.').check();
  await expect(dialog).toContainText('Review: R =');
  await dialog.getByRole('button', { name: 'Use reviewed impedance' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Existing source impedance is independent');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  await page.getByText('Advanced supply JSON').click();
  const supplyEditor = page.locator('#synthesis-supply');
  const source = JSON.parse(await supplyEditor.inputValue());
  delete source.motorStartingImpedance;
  await supplyEditor.fill(JSON.stringify(source)); await supplyEditor.press('Tab');
  await page.getByRole('button', { name: 'Review starting source impedance' }).click();
  dialog = page.getByRole('dialog', { name: 'Review starting source impedance' });
  await dialog.getByLabel('Starting-case source fault current (kA)').fill('17');
  await dialog.getByLabel('Starting-case source X/R').fill('2.5');
  await dialog.getByLabel('Source-case and X/R reference').fill('Synthetic starting source case');
  await dialog.getByLabel('These values describe the same source-only starting case at the stated source voltage.').check();
  await expect(dialog).toContainText('Review: R =');
  await dialog.getByRole('button', { name: 'Use reviewed impedance' }).click();
  await expect(dialog).toBeHidden();
  await expect(page.locator('#synthesis-status')).toContainText('Reviewed starting source impedance copied');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const pending = page.waitForEvent('download'); await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'));
  expect(proposal.loads).toHaveLength(count);
  expect(proposal.inputs.original.supply.motorStartingImpedanceBasis).toMatchObject({ faultCurrentKA: 17, xOverR: 2.5, reference: 'Synthetic starting source case' });
  expect(proposal.inputEvidence.records.supply.values.motorStartingImpedance.basis).toBe('source-case-derived');
  expect(proposal.sourceFaultConsistency.status).toBe('pass');
  await page.reload();
  const saved = JSON.parse(await supplyEditor.inputValue());
  expect(saved.motorStartingImpedanceBasis.faultCurrentKA).toBe(17);
  const voltage = page.locator('[data-synthesis-control="supply.voltage"]');
  await voltage.fill('416'); await voltage.press('Tab');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-output')).toContainText('Derived source-impedance basis');
  const stalePending = page.waitForEvent('download'); await page.locator('#synthesis-download-json').click();
  const stale = JSON.parse(await fs.readFile(await (await stalePending).path(), 'utf8'));
  expect(stale.issues.some(item => item.code === 'SOURCE_STARTING_BASIS_STALE')).toBe(true);
});
