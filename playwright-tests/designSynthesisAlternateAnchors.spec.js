import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Papa from 'papaparse';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

for (const count of [25, 50]) test(`${count} loads use explicit alternate field connections and retain their evidence after Apply`, async ({ page }) => {
  test.setTimeout(120000);
  const input = JSON.parse(await fs.readFile(path.join(root, 'samples/design-synthesis-industrial.json'), 'utf8'));
  const base = input.equipment;
  input.equipment = Array.from({ length: count }, (_, index) => ({ ...base[index % base.length], id: `L-${index}`, tag: `L-${index}`, kw: 1, x: 20, y: 0, z: 0 }));
  Object.assign(input.supply, { id: 'S', x: 0, y: 0, z: 0 });
  input.criteria.maxEndpointAttachmentFt = 4;
  input.corridors = { nodes: [{ id: 'N0', x: 0, y: 0, z: 0 }, { id: 'NA', x: 3, y: 0, z: 0 }, { id: 'N1', x: 20, y: 0, z: 0 }], edges: [{ id: 'A1', from: 'NA', to: 'N1', widthIn: 24, depthIn: 6, permitted: true }] };
  await page.goto(server.url('designsynthesis.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.locator('#synthesis-import').setInputFiles({ name: 'alternate-anchors.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(input)) });
  await expect(page.locator('#synthesis-status')).toContainText('Imported alternate-anchors.json');
  const policy = page.getByLabel('Alternative endpoint connections');
  await expect(policy).toHaveValue('nearest');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  await policy.selectOption('allow');
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal generated');
  await expect(page.locator('#synthesis-output')).toContainText('Alternative field connections: N0 → NA (3 ft)');
  await expect(page.locator('#synthesis-output')).toContainText('Field permission and obstacles require review');
  const jsonPending = page.waitForEvent('download');
  await page.locator('#synthesis-download-json').click();
  const proposal = JSON.parse(await fs.readFile(await (await jsonPending).path(), 'utf8'));
  const feeder = proposal.cables.find(row => !row.loadId);
  expect(feeder.lengthFt).toBe(20);
  expect(feeder.routingDecision.alternateEndpointAttachments.sourceNode).toBe('NA');
  expect(proposal.routeResults.batchResults.find(row => row.cable === feeder.id).route_segments.map(segment => segment.length)).toEqual([3, 17]);
  const csvPending = page.waitForEvent('download');
  await page.locator('#synthesis-download-cable-schedule').click();
  const csv = Papa.parse(await fs.readFile(await (await csvPending).path(), 'utf8'), { header: true, skipEmptyLines: true });
  expect(csv.errors).toEqual([]);
  const feederRow = csv.data.find(row => row['Cable ID'] === feeder.id);
  expect(feederRow['Alternative endpoint connection']).toBe('N0 to NA (3 ft); N1 to N1 (0 ft)');
  expect(feederRow['Field connection review']).toBe('Field permission and obstacles require review');
  const reportPending = page.waitForEvent('download');
  await page.locator('#synthesis-download-report').click();
  const report = await fs.readFile(await (await reportPending).path(), 'utf8');
  expect(report).toContain('Alternative field connections: N0 → NA (3 ft)');
  await page.locator('#synthesis-apply').click();
  await expect(page.getByRole('heading', { name: 'Create New Project' })).toBeVisible();
  await page.getByRole('dialog').locator('input[name="projectName"]').fill(`Alternate connection ${count}`);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.locator('[data-template-id="blank"]').click();
  await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Use Template', exact: true }).click()]);
  await expect(page.locator('#synthesis-apply')).toBeEnabled({ timeout: 60000 });
  await page.locator('#synthesis-apply').click();
  await page.waitForURL(/cableschedule\.html/);
  await page.waitForFunction(() => Boolean(window.dataStore));
  const readEvidence = () => page.evaluate(id => {
    const cable = window.dataStore.getCables().find(row => row.tag === id);
    const route = window.dataStore.getItem('latestRouteResults').batchResults.find(row => row.cable === id);
    return { cable: cable?.routingDecision?.alternateEndpointAttachments, route: route?.routingDecision?.alternateEndpointAttachments };
  }, feeder.id);
  await expect.poll(async () => (await readEvidence()).cable?.sourceNode).toBe('NA');
  expect((await readEvidence()).route).toEqual(feeder.routingDecision.alternateEndpointAttachments);
  await page.reload();
  await page.waitForFunction(() => Boolean(window.dataStore));
  await expect.poll(async () => (await readEvidence()).route?.sourceNode).toBe('NA');
  await page.goto(server.url('designsynthesis.html'));
  await expect(page.getByLabel('Alternative endpoint connections')).toHaveValue('allow');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-output')).toContainText('Alternative field connections: N0 → NA (3 ft)');
  await page.getByLabel('Alternative endpoint connections').selectOption('nearest');
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
});
