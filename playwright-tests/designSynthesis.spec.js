  test('refuses to overwrite a manually edited generated canonical record', async ({ page }) => {
    await page.goto(server.url('designsynthesis.html'));
    await page.evaluate(() => localStorage.clear());
    await page.reload();
    await expect(page.locator('#synthesis-equipment')).not.toHaveValue('');
    await page.click('#synthesis-generate');
    await page.click('#synthesis-apply');
    await page.getByRole('heading', { name: 'Create New Project' }).waitFor();
    await page.locator('input[id^="project-name-"]').fill('Manual Override Acceptance');
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    await page.locator('[data-template-id="blank"]').click();
    await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Use Template', exact: true }).click()]);
    await expect(page.locator('#synthesis-status')).toContainText('Proposal generated');
    await page.click('#synthesis-apply');
    await expect(page).toHaveURL(/cableschedule\.html/);
    await page.waitForFunction(() => typeof window.dataStore?.getCables === 'function');
    const edited = await page.evaluate(() => {
      const cables = window.dataStore.getCables();
      const next = cables.map((cable, index) => index === 0 ? { ...cable, conductorSize: 'MANUAL-EDIT', conductor_size: 'MANUAL-EDIT' } : cable);
      window.dataStore.setCables(next);
      if (!window.dataStore.saveProject(window.currentProjectId)) throw new Error('Manual edit must be saved before navigation');
      return next[0].id;
    });
    await page.goto(server.url('designsynthesis.html#Manual%20Override%20Acceptance'));
    await expect(page.locator('#synthesis-equipment')).not.toHaveValue('');
    await page.click('#synthesis-generate');
    await page.click('#synthesis-apply');
    await expect(page.locator('#synthesis-status')).toContainText(/blocked|conflict|manual/i);
    expect(await page.evaluate(id => window.dataStore.getCables().find(cable => cable.id === id)?.conductorSize, edited)).toBe('MANUAL-EDIT');
  });

