import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });

async function download(page, selector) {
  const pending = page.waitForEvent('download');
  await page.locator(selector).click();
  const value = await pending;
  const chunks = [];
  for await (const chunk of await value.createReadStream()) chunks.push(chunk);
  return Buffer.concat(chunks).toString();
}

test('starter sample exposes conditional assembly fit, preserves edits, rejects unsupported ratings and never enables motor Apply', async ({ page }, testInfo) => {
  await page.goto(server.url('designsynthesis.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Load motor starter sample', exact: true }).click();
  await expect(page.locator('#synthesis-status')).toContainText('Synthetic 25-load motor starter sample loaded');
  const hp = page.getByRole('spinbutton', { name: 'Motor nameplate horsepower 1', exact: true });
  const hz = page.getByRole('spinbutton', { name: 'Motor nameplate frequency (Hz) 1', exact: true });
  const coil = page.getByRole('spinbutton', { name: 'Starter control voltage (V)', exact: true });
  const coilType = page.getByRole('combobox', { name: 'Starter control current type', exact: true });
  const grounding = page.getByRole('combobox', { name: 'Source grounding', exact: true });
  const review = page.locator('#synthesis-motor-starter-review');
  await expect(hp).toHaveValue('10');
  await expect(hz).toHaveValue('60');
  await expect(grounding).toHaveValue('solid');
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  await expect(review).toContainText('3RT2025-1BB40 + 3RU2126-4AB0 + 3RV2021-4AA10');
  await expect(review).toContainText('candidate dial 12.8 A');
  await expect(review).toContainText('published nominal trip calibration 16 A');
  await expect(review).toContainText('actual controller setting unspecified');
  await expect(review).toContainText('not an assembled-panel SCCR');
  await expect(review).toContainText('enclosureOrientation — unevaluated');
  const proposal = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(proposal.loads).toHaveLength(25);
  expect(proposal.motorStarterCandidates.status).toBe('blocked');
  expect(proposal.motorStarterCandidates.cases[0].candidate.selectedForApply).toBe(false);
  expect(proposal.motorOverloadCandidates.cases[0].candidate.catalogNumber).toBe('3RU2116-4AB0');
  const report = (await download(page, '#synthesis-download-report')).split('Complete JSON payload:')[0];
  for (const text of ['3RT2025-1BB40', '3RU2126-4AB0', '3RV2021-4AA10', 'enclosureOrientation [unevaluated]', 'certifiedControllerCondition [unevaluated]', 'not an assembled-panel SCCR', '3RU2126_CoC_202505131337157102.pdf']) expect(report).toContain(text);
  expect(report).not.toContain('[object Object]');
  expect(report).toContain('alternative proposals, not two installed relays');
  await fs.writeFile(testInfo.outputPath('starter-review-report.txt'), report);
  await page.setViewportSize({ width: 1280, height: 1100 });
  await review.scrollIntoViewIfNeeded();
  await page.evaluate(() => window.scrollBy(0, -80));
  await review.screenshot({ path: testInfo.outputPath('starter-review.png') });

  await hp.fill('15');
  await hp.press('Tab');
  await expect(hz).toBeFocused();
  await hz.fill('60');
  await hz.press('Tab');
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await expect(page.locator('#synthesis-download-report')).toBeDisabled();
  await expect(review).toHaveCount(0);
  await page.locator('#synthesis-generate').click();
  const rejected = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(rejected.inputSignature).not.toBe(proposal.inputSignature);
  expect(rejected.motorStarterCandidates.cases[0].candidate).toBeNull();
  await expect(review).toContainText('ulHorsepower — fail');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const rejectedReport = (await download(page, '#synthesis-download-report')).split('Complete JSON payload:')[0];
  expect(rejectedReport).toContain('Rejected candidate:');
  expect(rejectedReport).toContain('ulHorsepower [fail]');
  expect(rejectedReport).toContain('3RU2126_CoC_202505131337157102.pdf');
  await fs.writeFile(testInfo.outputPath('starter-rejected-report.txt'), rejectedReport);

  await hp.fill('10');
  await hp.press('Tab');
  await coil.fill('120');
  await coil.press('Tab');
  await expect(coilType).toBeFocused();
  await coilType.selectOption('AC');
  await grounding.selectOption('resistance');
  await page.locator('#synthesis-generate').click();
  await expect(review).toContainText('controlSupply — fail');
  await expect(review).toContainText('slashVoltageSystem — fail');
  const unsuitable = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(unsuitable.motorStarterCandidates.cases[0].candidate.selectedForApply).toBe(false);
  expect(unsuitable.inputs.original.criteria.motorStarter.controlVoltageV).toBe(120);
  expect(unsuitable.inputs.original.criteria.motorStarter.controlCurrentType).toBe('AC');
  expect(unsuitable.inputs.original.supply.voltageSystem.grounding).toBe('resistance');
  await page.reload();
  await expect(coil).toHaveValue('120');
  await expect(coilType).toHaveValue('AC');
  await expect(grounding).toHaveValue('resistance');
  await expect(hp).toHaveValue('10');
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await coil.fill('24');
  await coil.press('Tab');
  await coilType.selectOption('DC');
  await grounding.selectOption('solid');
  await page.locator('#synthesis-generate').click();
  const restored = JSON.parse(await download(page, '#synthesis-download-json'));
  const checks = restored.motorStarterCandidates.cases[0].candidate.checks;
  expect(checks.find(row => row.id === 'controlSupply').status).toBe('pass');
  expect(checks.find(row => row.id === 'slashVoltageSystem').status).toBe('pass');
  expect(checks.find(row => row.id === 'faultDutyAndCoordination').status).toBe('unevaluated');
  expect(restored.status).toBe('blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  await hz.fill('50');
  await hz.press('Tab');
  await expect(page.locator('#synthesis-download-json')).toBeDisabled();
  await page.locator('#synthesis-generate').click();
  const wrongFrequency = JSON.parse(await download(page, '#synthesis-download-json'));
  expect(wrongFrequency.issues.some(row => row.code === 'UNSUPPORTED_MOTOR_NAMEPLATE_FREQUENCY')).toBe(true);
  expect(wrongFrequency.motorStartingValidation?.status).not.toBe('pass');
  await expect(review).toHaveCount(0);
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  await hz.fill('60');
  await hz.press('Tab');
  await page.locator('#synthesis-generate').click();
  await expect(review).toContainText('3RT2025-1BB40 + 3RU2126-4AB0 + 3RV2021-4AA10');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
});
