import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startStaticServer } from './staticServer.helper.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let server;
test.beforeAll(async () => { server = await startStaticServer(root); });
test.afterAll(async () => { await server?.close(); });
test.beforeEach(async ({ page }) => {
  await page.goto(server.url('designsynthesis.html?e2e=1'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await expect(page.locator('#synthesis-equipment')).not.toHaveValue('');
});

test('generated equipment and cable data run a nonzero-loss load flow through the normal study page', async ({ page }, testInfo) => {
  test.setTimeout(60000);
  await page.goto(server.url('designsynthesis.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal generated');
  await page.locator('#synthesis-apply').click();
  await expect(page.getByRole('heading', { name: 'Create New Project' })).toBeVisible();
  await page.locator('input[id^="project-name-"]').fill('Synthesis Study Handoff');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Choose a Project Template' })).toBeVisible();
  await page.locator('[data-template-id="blank"]').click();
  await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Use Template', exact: true }).click()]);
  await expect(page.locator('#synthesis-status')).toContainText('Proposal generated');
  await page.locator('#synthesis-apply').click();
  await expect(page).toHaveURL(/cableschedule\.html/);
  await page.goto(`${server.url('loadFlow.html')}#Synthesis%20Study%20Handoff`);
  await page.locator('input[name="baseMVA"]').fill('1');
  await page.locator('#loadflow-form button[type="submit"]').click();
  await expect(page.locator('#loadflow-output')).toContainText('Bus Voltages');
  const result = await page.evaluate(() => window.dataStore.getStudies().loadFlow);
  const assessment = await page.evaluate(() => window.dataStore.getStudyAssessments().loadFlow);
  expect(assessment, JSON.stringify(assessment)).toMatchObject({ eligible: true });
  await expect(page.locator('#export-loadflow-btn')).toBeEnabled();
  expect(result.converged).toBe(true);
  expect(result.persisted).toBe(true);
  expect(result.inputReadiness.counts).toMatchObject({ buses: 35, branches: 34, slackBuses: 1 });
  expect(result.summary.totalLoadKW).toBeCloseTo(876, 7);
  expect(result.losses.P).toBeGreaterThan(0.1);
  expect(Math.min(...result.buses.map(bus => bus.Vm))).toBeLessThan(0.999);
  expect(new Set(result.lines.map(line => line.id)).size).toBe(34);
  const cables = await page.evaluate(() => window.dataStore.getCables());
  for (const cable of cables) expect(result.lines.find(line => line.id === cable.id)?.rating).toBe(cable.ampacityA);
  expect(result.summary.totalGenKW).toBeCloseTo(876 + result.losses.P, 2);
  await page.locator('#loadflow-output').screenshot({ path: testInfo.outputPath('synthesis-load-flow.png') });
  const pending = page.waitForEvent('download');
  await page.locator('#export-loadflow-btn').click();
  const download = await pending;
  expect(download.suggestedFilename()).toBe('loadflow.pdf');
  expect((await fs.readFile(await download.path())).subarray(0, 5).toString()).toBe('%PDF-');
  await page.locator('input[name="baseMVA"]').fill('2');
  await expect(page.locator('#export-loadflow-btn')).toBeDisabled();
});

test('blocked input retains every equipment row and explains rejected and deferred dispositions', async ({ page }, testInfo) => {
  const input = JSON.parse(await fs.readFile(path.join(root, 'samples/design-synthesis-industrial.json'), 'utf8'));
  input.equipment[0].kw = -1;
  input.equipment[1] = null;
  await page.locator('#synthesis-import').setInputFiles({ name: 'invalid-equipment.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(input)) });
  await page.locator('#synthesis-generate').click();
  await expect(page.locator('#synthesis-status')).toContainText('Proposal blocked');
  await expect(page.locator('#synthesis-apply')).toBeDisabled();
  const rows = page.locator('#synthesis-load-dispositions tbody tr');
  await expect(rows).toHaveCount(30);
  await expect(rows.nth(0)).toContainText('rejected');
  await expect(rows.nth(0)).toContainText('positive');
  await expect(rows.nth(1)).toContainText('rejected');
  await expect(rows.nth(2)).toContainText('deferred');
  await expect(rows.nth(2)).not.toContainText('accepted');
  const pending = page.waitForEvent('download');
  await page.locator('#synthesis-download-report').click();
  const report = (await fs.readFile(await (await pending).path(), 'utf8')).split('Complete JSON payload:')[0];
  expect(report).toContain('Equipment disposition:');
  expect(report).toMatch(/input row 1;.*status rejected/);
  expect(report).toMatch(/input row 2;.*status rejected/);
  expect(report).toMatch(/input row 30;.*status deferred/);
  expect(report).not.toContain('Generated load accepted');
  await rows.nth(2).screenshot({ path: testInfo.outputPath('deferred-load.png') });
});
